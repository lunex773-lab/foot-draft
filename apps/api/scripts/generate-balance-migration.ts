/**
 * Generates migrations/0013_card_balance.sql: the card balance of decisions
 * 118-122 (packages/shared/src/players/balance.ts) for the cards already in
 * D1. OVR, the six card stats, the SIM attributes and the special abilities
 * of every card are set to the values of the catalog; ids, owned cards,
 * strengthening levels and past matches stay as they are.
 *
 *   npm run seed:balance -w @fd/api
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { getCatalog } from '@fd/shared';

const q = (v: string | number) => (typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`);
const NOW = 1795132800000; // fixed timestamp (2026-11-20) so the file is reproducible

const players = getCatalog();
const lines: string[] = [
  '-- GENERATED by scripts/generate-balance-migration.ts. Do not edit by hand.',
  '-- Card balance (decisions 118-122): OVR bands by rarity (COMMON 45-59, RARE 60-69, EPIC 70-79,',
  '-- LEGENDARY 80-89, ICON 90-99; stats and SIM attributes move with OVR) and special abilities',
  '-- (ICON 2 incl. one ICON-only, EPIC / LEGENDARY 1, COMMON / RARE none).',
  `DELETE FROM player_traits WHERE player_id IN (${players.map((p) => q(p.id)).join(',')});`,
];
for (const p of players) {
  const s = p.stats;
  lines.push(`UPDATE player_cards SET ovr = ${p.ovr}, pac = ${s.pac}, sho = ${s.sho}, pas = ${s.pas}, dri = ${s.dri}, def = ${s.def}, phy = ${s.phy}, updated_at = ${NOW} WHERE id = ${q(p.id)};`);
  const a = p.attributes;
  lines.push(
    `UPDATE player_attributes SET acceleration = ${a.acceleration}, sprint_speed = ${a.sprintSpeed}, shot_accuracy = ${a.shotAccuracy}, shot_power = ${a.shotPower}, finishing = ${a.finishing}, short_passing = ${a.shortPassing}, long_passing = ${a.longPassing}, vision = ${a.vision}, ball_control = ${a.ballControl}, dribbling = ${a.dribbling}, tackling = ${a.tackling}, interception = ${a.interception}, positioning = ${a.positioning}, stamina = ${a.stamina}, strength = ${a.strength}, jumping = ${a.jumping}, gk_reflexes = ${a.gkReflexes}, gk_handling = ${a.gkHandling}, gk_positioning = ${a.gkPositioning} WHERE player_id = ${q(p.id)};`,
  );
  p.traits.forEach((t, i) => lines.push(`INSERT INTO player_traits VALUES (${q(p.id)},${q(t)},${i});`));
}
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'migrations', '0013_card_balance.sql');
writeFileSync(out, `${lines.join('\n')}\n`);
console.log(`wrote ${out} (${players.length} cards, ${players.reduce((n, p) => n + p.traits.length, 0)} abilities)`);
