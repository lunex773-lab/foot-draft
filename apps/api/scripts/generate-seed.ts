/**
 * Generates migrations/0003_player_db_v1.sql from the player database
 * (data/player-db-v1, loaded through @fd/shared getCatalog()).
 *
 *   npm run seed:generate -w @fd/api
 *
 * 0002_seed_players.sql (the retired generated 240-card catalog) is kept as
 * a historical migration; 0003 deactivates those cards so that past drafts
 * and matches stay valid, and inserts the 300 database cards.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOG_VERSION, getCatalog } from '@fd/shared';

const q = (v: string | number) => (typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`);
const NOW = 1763020800000; // fixed timestamp so the file is reproducible

const players = getCatalog();
const lines: string[] = [
  '-- GENERATED by scripts/generate-seed.ts. Do not edit by hand.',
  `-- FOOTBALL DRAFT 300 Player Database v1: ${players.length} fictional player cards (catalog version ${CATALOG_VERSION})`,
  'ALTER TABLE player_cards ADD COLUMN card_asset TEXT;',
  `UPDATE player_cards SET is_active = 0, updated_at = ${NOW} WHERE catalog_version < ${CATALOG_VERSION};`,
];
for (const p of players) {
  // appearance_json / preferred_foot are not part of the database (NOT NULL columns from v1)
  lines.push(
    `INSERT INTO player_cards (id,name,first_name,last_name,nationality,league_id,club_id,rarity,primary_position,ovr,role,pac,sho,pas,dri,def,phy,age,preferred_foot,height_cm,appearance_json,card_asset,catalog_version,is_active,created_at,updated_at) VALUES (${[
      p.id, p.name, p.firstName, p.lastName, p.nationality, p.leagueId, p.clubId, p.rarity, p.primaryPosition, p.ovr, p.role,
      p.stats.pac, p.stats.sho, p.stats.pas, p.stats.dri, p.stats.def, p.stats.phy, p.age, '', p.heightCm, '{}', p.cardAsset, CATALOG_VERSION, 1, NOW, NOW,
    ].map(q).join(',')});`,
  );
  const a = p.attributes;
  lines.push(
    `INSERT INTO player_attributes VALUES (${[p.id, a.acceleration, a.sprintSpeed, a.shotAccuracy, a.shotPower, a.finishing, a.shortPassing, a.longPassing, a.vision, a.ballControl, a.dribbling, a.tackling, a.interception, a.positioning, a.stamina, a.strength, a.jumping, a.gkReflexes, a.gkHandling, a.gkPositioning].map(q).join(',')});`,
  );
  p.positions.forEach((pos, i) => lines.push(`INSERT INTO player_positions VALUES (${q(p.id)},${q(pos)},${i === 0 ? 1 : 0},${i});`));
  p.traits.forEach((t, i) => lines.push(`INSERT INTO player_traits VALUES (${q(p.id)},${q(t)},${i});`));
}
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'migrations', '0003_player_db_v1.sql');
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${players.length} players to ${out}`);
