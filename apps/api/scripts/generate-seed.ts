/**
 * Generates migrations/0002_seed_players.sql from the deterministic catalog
 * in @fd/shared. Run after changing the generator:
 *   npm run seed:generate -w @fd/api
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CATALOG_VERSION, generateCatalog } from '@fd/shared';

const q = (v: string | number) => (typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`);
const NOW = 1763000000000; // fixed timestamp so the file is reproducible

const players = generateCatalog();
const lines: string[] = [
  '-- GENERATED by scripts/generate-seed.ts. Do not edit by hand.',
  `-- ${players.length} fictional player cards (catalog version ${CATALOG_VERSION})`,
];
for (const p of players) {
  lines.push(
    `INSERT INTO player_cards (id,name,first_name,last_name,nationality,league_id,club_id,rarity,primary_position,ovr,role,pac,sho,pas,dri,def,phy,age,preferred_foot,height_cm,appearance_json,catalog_version,is_active,created_at,updated_at) VALUES (${[
      p.id, p.name, p.firstName, p.lastName, p.nationality, p.leagueId, p.clubId, p.rarity, p.primaryPosition, p.ovr, p.role,
      p.stats.pac, p.stats.sho, p.stats.pas, p.stats.dri, p.stats.def, p.stats.phy, p.age, p.preferredFoot, p.heightCm,
      JSON.stringify(p.appearance), CATALOG_VERSION, 1, NOW, NOW,
    ].map(q).join(',')});`,
  );
  const a = p.attributes;
  lines.push(
    `INSERT INTO player_attributes VALUES (${[p.id, a.acceleration, a.sprintSpeed, a.shotAccuracy, a.shotPower, a.finishing, a.shortPassing, a.longPassing, a.vision, a.ballControl, a.dribbling, a.tackling, a.interception, a.positioning, a.stamina, a.strength, a.jumping, a.gkReflexes, a.gkHandling, a.gkPositioning].map(q).join(',')});`,
  );
  p.positions.forEach((pos, i) => lines.push(`INSERT INTO player_positions VALUES (${q(p.id)},${q(pos)},${i === 0 ? 1 : 0},${i});`));
  p.traits.forEach((t, i) => lines.push(`INSERT INTO player_traits VALUES (${q(p.id)},${q(t)},${i});`));
}
const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'migrations', '0002_seed_players.sql');
writeFileSync(out, lines.join('\n') + '\n');
console.log(`wrote ${players.length} players to ${out}`);
